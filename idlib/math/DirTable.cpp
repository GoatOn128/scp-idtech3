/*
================
DirToByte

this isn't a real cheap function to call!
================
*/
int DirToByte( const idVec3 &dir ) {
	int i, best;
	float d, bestd;

	bestd = 0;
	best = 0;
	for ( i = 0 ; i < NUMVERTEXNORMALS ; i++ ) {
		d = dir * bytedirs[i];
		if ( d > bestd ) {
			bestd = d;
			best = i;
		}
	}

	return best;
}

/*
================
ByteToDir
================
*/
void ByteToDir( int b, idVec3 &dir ) {
	if ( b < 0 || b >= NUMVERTEXNORMALS ) {
		dir = vec3_origin;
		return;
	}
	dir = bytedirs[b];
}
